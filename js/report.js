const resourceCards = document.querySelectorAll('[data-resource]');
const resourceModal = document.querySelector('#resource-modal');

if (resourceCards.length && resourceModal) {
  const modalPanel = resourceModal.querySelector('.modal-panel');
  const categoryButtons = resourceModal.querySelectorAll('[data-modal-target]');
  let previouslyFocused = null;

  const setText = (selector, value) => {
    const element = resourceModal.querySelector(selector);
    if (element) element.textContent = value;
  };

  const renderFacts = (facts) => {
    const container = resourceModal.querySelector('[data-modal-facts]');
    container.replaceChildren(...facts.map(([label, value]) => {
      const row = document.createElement('div');
      const term = document.createElement('dt');
      const description = document.createElement('dd');
      term.textContent = label;
      description.textContent = value;
      row.append(term, description);
      return row;
    }));
  };

  const renderPrograms = (programs) => {
    const container = resourceModal.querySelector('[data-modal-programs]');
    container.replaceChildren(...programs.map(([index, title, description, meta]) => {
      const item = document.createElement('article');
      item.className = 'program-item';
      const number = document.createElement('span');
      number.className = 'program-index';
      number.textContent = `PROGRAM ${index}`;
      const heading = document.createElement('h4');
      heading.textContent = title;
      const copy = document.createElement('p');
      copy.textContent = description;
      const information = document.createElement('span');
      information.className = 'program-meta';
      information.textContent = meta;
      item.append(number, heading, copy, information);
      return item;
    }));
  };

  const renderReviews = (reviews) => {
    const container = resourceModal.querySelector('[data-modal-reviews]');
    container.replaceChildren(...reviews.map(([profile, rating, review]) => {
      const item = document.createElement('article');
      item.className = 'review-item';
      const user = document.createElement('div');
      user.className = 'review-profile';
      const name = document.createElement('strong');
      name.textContent = profile;
      const score = document.createElement('span');
      score.textContent = rating;
      const quote = document.createElement('blockquote');
      quote.textContent = review;
      user.append(name, score);
      item.append(user, quote);
      return item;
    }));
  };

  const openModal = (key, trigger) => {
    const resource = resourceData[key];
    if (!resource) return;

    setText('[data-modal-number]', resource.number);
    setText('[data-modal-type]', resource.type);
    setText('[data-modal-title]', resource.title);
    setText('[data-modal-summary]', resource.summary);
    setText('[data-modal-location]', resource.location);
    setText('[data-modal-season]', resource.season);
    setText('[data-modal-description]', resource.description);
    renderFacts(resource.facts);
    renderPrograms(resource.programs);
    renderReviews(resource.reviews);

    previouslyFocused = trigger;
    modalPanel.scrollTop = 0;
    categoryButtons.forEach((button, index) => button.classList.toggle('active', index === 0));
    resourceModal.classList.add('open');
    resourceModal.setAttribute('aria-hidden', 'false');
    document.body.classList.add('modal-open');
    window.setTimeout(() => resourceModal.querySelector('.modal-close').focus(), 60);
  };

  const closeModal = () => {
    resourceModal.classList.remove('open');
    resourceModal.setAttribute('aria-hidden', 'true');
    document.body.classList.remove('modal-open');
    if (previouslyFocused) previouslyFocused.focus();
  };

  resourceCards.forEach((card) => {
    card.addEventListener('click', () => openModal(card.dataset.resource, card));
    card.addEventListener('keydown', (event) => {
      if (event.key === 'Enter' || event.key === ' ') {
        event.preventDefault();
        openModal(card.dataset.resource, card);
      }
    });
  });

  resourceModal.querySelectorAll('[data-modal-close]').forEach((button) => {
    button.addEventListener('click', closeModal);
  });

  categoryButtons.forEach((button) => {
    button.addEventListener('click', () => {
      const target = resourceModal.querySelector(`#${button.dataset.modalTarget}`);
      if (!target) return;
      const navHeight = resourceModal.querySelector('.modal-category-nav').offsetHeight;
      const scrollTop = target.getBoundingClientRect().top - modalPanel.getBoundingClientRect().top + modalPanel.scrollTop - navHeight;
      modalPanel.scrollTo({ top: scrollTop, behavior: 'smooth' });
      categoryButtons.forEach((item) => item.classList.toggle('active', item === button));
    });
  });

  document.addEventListener('keydown', (event) => {
    if (!resourceModal.classList.contains('open')) return;
    if (event.key === 'Escape') closeModal();

    if (event.key === 'Tab') {
      const focusable = [...resourceModal.querySelectorAll('button:not([disabled]), [href], [tabindex]:not([tabindex="-1"])')]
        .filter((element) => element.offsetParent !== null);
      if (!focusable.length) return;
      const first = focusable[0];
      const last = focusable[focusable.length - 1];
      if (event.shiftKey && document.activeElement === first) {
        event.preventDefault();
        last.focus();
      } else if (!event.shiftKey && document.activeElement === last) {
        event.preventDefault();
        first.focus();
      }
    }
  });
}
